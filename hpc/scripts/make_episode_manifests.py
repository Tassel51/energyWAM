#!/usr/bin/env python
"""Deterministic, episode-disjoint train/val(/test) episode manifests.

Produces the ``energywam_episode_manifest_v1`` JSON files consumed by
``scripts/fit_normalization_stats.py`` (``--episodes-manifest`` /
``--val-manifest`` / ``--test-manifest``) and by
``scripts/evaluate.py --eval-episodes-manifest``.

Design constraints
------------------
* **Episode-disjoint by construction** — the manifests form a partition of the
  episode index set; no episode can appear in two splits.
* **Deterministic and Python-version independent** — the ordering is a
  SHA-256 keyed sort of ``f"{seed}:{episode_index}"``, not ``random.shuffle``
  (whose stream is not guaranteed stable across CPython versions).  The same
  dataset + seed always yields byte-identical manifests.
* **Real data only** — this tool refuses to run without a real LeRobot dataset
  tree (``meta/info.json`` present).  There is no synthetic mode; synthetic
  manifests belong to the test helpers, never to a training run.
* **No statistics are fitted here** — this is a pure index split.  Statistics
  come from ``scripts/fit_normalization_stats.py`` on the TRAIN manifest only.

Usage::

    python hpc/scripts/make_episode_manifests.py \\
        --dataset-root /path/to/.../20250816/lerobot \\
        --out-dir manifests/opendrawer \\
        --seed 20261029 --val-frac 0.1

    # or take the root from a run config (data_root_dir / data_mix)
    python hpc/scripts/make_episode_manifests.py \\
        --config hpc/configs/hpc_smoke_gpu.yaml --out-dir manifests/opendrawer
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Dict, List, Sequence

# --- import bootstrap: hpc/scripts -> hpc -> repo root -----------------------
_HERE = Path(__file__).resolve()
_ROOT = next(
    (p for p in _HERE.parents if (p / "energywam").is_dir()),
    _HERE.parents[2],
)
sys.path.insert(0, str(_ROOT))

MANIFEST_SCHEMA_VERSION = "energywam_episode_manifest_v1"
SPLIT_NAMES = ("train", "val", "test")


def deterministic_order(indices: Sequence[int], seed: int) -> List[int]:
    """Total order on episode indices that is stable across Python versions.

    Key is ``sha256(f"{seed}:{episode}")``; ties broken by the index itself,
    so the result is a strict permutation of ``indices``.
    """
    def key(e: int) -> bytes:
        return hashlib.sha256(f"{int(seed)}:{int(e)}".encode("utf-8")).digest()

    return sorted((int(e) for e in indices), key=lambda e: (key(e), e))


def split_counts(n: int, val_frac: float, test_frac: float) -> Dict[str, int]:
    """Non-overlapping integer counts summing to ``n`` (val/test take the floor)."""
    if n < 3:
        raise SystemExit(f"need at least 3 episodes to make a disjoint split, got {n}")
    if not (0.0 <= val_frac < 1.0) or not (0.0 <= test_frac < 1.0):
        raise SystemExit(f"val/test fractions must be in [0,1), got {val_frac}, {test_frac}")
    if val_frac + test_frac >= 1.0:
        raise SystemExit(f"val_frac+test_frac must be < 1, got {val_frac + test_frac}")
    n_val = int(n * val_frac)
    n_test = int(n * test_frac)
    n_train = n - n_val - n_test
    if n_train < 1:
        raise SystemExit(
            f"split leaves no training episode (n={n}, val={n_val}, test={n_test})"
        )
    return {"train": n_train, "val": n_val, "test": n_test}


def build_manifest(
    *,
    split: str,
    episodes: Sequence[int],
    dataset_identity: str,
    dataset_root: str,
    seed: int,
    val_frac: float,
    test_frac: float,
    max_episodes: int | None,
    notes_extra: str = "",
) -> Dict[str, object]:
    notes = (
        f"deterministic episode-disjoint split; "
        f"order=sha256(f'{seed}:{{episode_index}}') sorted ascending; "
        f"partition of {len(episodes)} episodes into "
        f"train/val/test at fractions (1-{val_frac}-{test_frac}); "
        f"val/test counts take the floor, train takes the remainder; "
        f"no synthetic episodes; generated by hpc/scripts/make_episode_manifests.py"
    )
    if max_episodes is not None:
        notes += f"; capped to the first {max_episodes} episodes of the deterministic order"
    if notes_extra:
        notes += f"; {notes_extra}"
    return {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "split": split,
        "dataset_identity": dataset_identity,
        "dataset_root": dataset_root,
        "episode_indices": [int(e) for e in episodes],
        "notes": notes,
    }


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--config", default=None,
                    help="run config whose data_root_dir/data_mix locate the dataset")
    ap.add_argument("--dataset-root", default=None,
                    help="explicit LeRobot dataset directory (overrides --config)")
    ap.add_argument("--out-dir", required=True, help="directory for the split manifests")
    ap.add_argument("--seed", type=int, default=20261029,
                    help="split seed (default 20261029); same seed => same split")
    ap.add_argument("--val-frac", type=float, default=0.1,
                    help="fraction of episodes held out as val (floor)")
    ap.add_argument("--test-frac", type=float, default=0.0,
                    help="fraction of episodes held out as test (floor)")
    ap.add_argument("--max-episodes", type=int, default=None,
                    help="SMOKE ONLY: cap the total number of episodes considered")
    ap.add_argument("--notes", default="", help="extra provenance appended to each manifest")
    ap.add_argument("--overwrite", action="store_true",
                    help="allow replacing existing manifest files")
    ap.add_argument("--set", nargs="*", default=[], help="KEY=VALUE dotlist config overrides")
    args = ap.parse_args()

    from energywam.data.episode_dataset import LeRobotEpisodeReader

    # --- locate a REAL dataset tree (no synthetic path exists here) ---------
    if args.dataset_root:
        root = Path(args.dataset_root)
    elif args.config:
        from energywam.config import load_config
        from energywam.data.energy_dataset import resolve_dataset_root

        root = resolve_dataset_root(load_config(args.config, overrides=args.set))
    else:
        raise SystemExit("give either --dataset-root or --config")
    root = root.resolve()
    if not (root / "meta" / "info.json").exists():
        raise SystemExit(
            f"{root} is not a LeRobot dataset (no meta/info.json).  Manifests are "
            "generated from REAL data only; there is no synthetic mode."
        )

    reader = LeRobotEpisodeReader(root)
    all_eps = sorted(int(e["episode_index"]) for e in reader.episodes)
    if not all_eps:
        raise SystemExit(f"{root} reports zero episodes")
    identity = reader.dataset_identity

    ordered = deterministic_order(all_eps, args.seed)
    if args.max_episodes is not None:
        if args.max_episodes < 3:
            raise SystemExit("--max-episodes must be >= 3 to keep a disjoint split")
        ordered = ordered[: args.max_episodes]
        notes_extra = f"SMOKE SUBSET: {args.max_episodes} of {len(all_eps)} episodes"
    else:
        notes_extra = ""

    counts = split_counts(len(ordered), args.val_frac, args.test_frac)
    cursor = 0
    assignment: Dict[str, List[int]] = {}
    for name in SPLIT_NAMES:
        take = counts[name]
        assignment[name] = ordered[cursor : cursor + take]
        cursor += take

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: Dict[str, str] = {}
    for name in SPLIT_NAMES:
        if not assignment[name]:
            # e.g. --test-frac 0: no manifest is written at all, so nothing
            # downstream can mistake an empty split for a real held-out set.
            print(f"[manifests] {name}: 0 episodes (split not requested, no file written)")
            continue
        path = out_dir / f"{name}_episodes.json"
        if path.exists() and not args.overwrite:
            raise SystemExit(f"refusing to overwrite {path}; pass --overwrite")
        man = build_manifest(
            split=name,
            episodes=assignment[name],
            dataset_identity=identity,
            dataset_root=str(root),
            seed=args.seed,
            val_frac=args.val_frac,
            test_frac=args.test_frac,
            max_episodes=args.max_episodes,
            notes_extra=notes_extra,
        )
        path.write_text(json.dumps(man, indent=2) + "\n")
        written[name] = str(path)
        print(f"[manifests] {name}: {len(man['episode_indices'])} episodes -> {path}")

    # --- independent validation with the project's own loader ---------------
    from energywam.data.stats_fit import load_episode_manifest

    report = {
        "dataset_root": str(root),
        "dataset_identity": identity,
        "total_episodes_in_dataset": len(all_eps),
        "episodes_considered": len(ordered),
        "seed": args.seed,
        "val_frac": args.val_frac,
        "test_frac": args.test_frac,
        "max_episodes": args.max_episodes,
        "counts": {k: len(v) for k, v in assignment.items()},
        "manifests": {},
    }
    for name, path in written.items():
        man, eps = load_episode_manifest(
            path,
            reader=reader,
            expect_split=name,
            other_manifest_paths=[p for n, p in written.items() if n != name],
        )
        report["manifests"][name] = {
            "path": path,
            "num_episodes": len(eps),
            "manifest_sha256": man["manifest_sha256"],
        }
    report_path = out_dir / "split_report.json"
    if report_path.exists() and not args.overwrite:
        raise SystemExit(f"refusing to overwrite {report_path}; pass --overwrite")
    report_path.write_text(json.dumps(report, indent=2) + "\n")
    print(f"[manifests] split report -> {report_path}")
    print(f"[manifests] dataset_identity={identity} (root={root})")
    print("[manifests] verified: disjoint, every episode exists, no duplicates")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
